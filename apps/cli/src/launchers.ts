import { access, chmod, rm, writeFile, constants as fsConstants } from "node:fs/promises";
import path from "node:path";

import { isSourceCheckout } from "./sync.ts";

// The install directory keeps two tiny launchers so `./oneself.sh update` keeps
// working. They contain no install logic: they only forward to bin/oneself with
// ONESELF_DIR set to their own directory. The CLI is the single implementation.

/** POSIX launcher written to <install>/oneself.sh. */
export function unixLauncher(): string {
  return `#!/bin/sh
# OneSelf launcher. No install logic lives here: it forwards to the CLI binary
# in this directory. Regenerated by \`oneself install\` / \`oneself update\`.
set -eu
here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
bin="$here/bin/oneself"
if [ ! -x "$bin" ]; then
  printf 'oneself: 找不到 %s，请重新运行 Release 的安装命令（curl … | sh）\\n' "$bin" >&2
  exit 1
fi
if [ "$#" -eq 0 ]; then
  set -- install
fi
ONESELF_DIR=$here
export ONESELF_DIR
exec "$bin" "$@"
`;
}

/** PowerShell launcher written to <install>\\oneself.ps1 (run with -File, so exit is safe). */
export function windowsLauncher(): string {
  return `# OneSelf launcher. No install logic lives here: it forwards to the CLI binary
# in this directory. Run it with: powershell -ExecutionPolicy Bypass -File oneself.ps1 <command>
# Regenerated by \`oneself install\` / \`oneself update\`.
$ErrorActionPreference = 'Stop'
$bin = Join-Path $PSScriptRoot 'bin\\oneself.exe'
if (-not (Test-Path -LiteralPath $bin)) {
  [Console]::Error.WriteLine("oneself: 找不到 $bin，请重新运行 Release 的安装命令（irm … | iex）")
  exit 1
}
$cliArgs = if ($args.Count -eq 0) { @('install') } else { @($args) }
$env:ONESELF_DIR = $PSScriptRoot
& $bin @cliArgs
exit $LASTEXITCODE
`;
}

async function exists(target: string): Promise<boolean> {
  try {
    await access(target, fsConstants.F_OK);
    return true;
  } catch {
    return false;
  }
}

/**
 * Write the thin launchers next to bin/oneself and drop the full shell installers
 * that older compose bundles left under deploy/. Skipped when no CLI binary is
 * installed (e.g. running the CLI from source with node), because a launcher
 * without a binary would only print an error. Never touches a source checkout.
 */
export async function installLaunchers(
  root: string,
  platform: NodeJS.Platform = process.platform,
): Promise<boolean> {
  const binary = path.join(root, "bin", platform === "win32" ? "oneself.exe" : "oneself");
  if (await isSourceCheckout(root)) return false;
  if (!(await exists(binary))) return false;
  const sh = path.join(root, "oneself.sh");
  await writeFile(sh, unixLauncher(), { mode: 0o755 });
  await chmod(sh, 0o755);
  await writeFile(path.join(root, "oneself.ps1"), windowsLauncher().replace(/\n/g, "\r\n"));
  for (const stale of ["oneself.sh", "oneself.ps1"]) {
    await rm(path.join(root, "deploy", stale), { force: true });
  }
  return true;
}
